//! Directory listings, computed from the bundle on demand (spec §10).
//!
//! OKF §6 lets a folder have an `index.md` that lists what it holds. Tessela does
//! not keep those files: a listing is a query, so it is never stale and never causes
//! git churn. `write_indexes` exists for bundles that are read by tools that do not
//! compute listings themselves.

use std::collections::{BTreeMap, BTreeSet};
use std::io;
use std::path::Path;

use serde::Serialize;

use crate::bundle::Bundle;
use crate::page::Page;

/// First line of a generated `index.md`'s body. `write_indexes` only replaces files
/// that carry it, so a hand-written `index.md` is never overwritten by accident.
pub const MARKER: &str =
    "<!-- generated by `tessela index`; remove this line to keep the file as it is -->";

const DESCRIPTION_CHARS: usize = 120;

#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct PageEntry {
    /// Path inside the bundle, e.g. `project/tessela.md`.
    pub path: String,
    pub title: String,
    /// The frontmatter `description`, or else the first line of the page.
    pub description: Option<String>,
    #[serde(rename = "type")]
    pub kind: Option<String>,
}

#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct FolderEntry {
    /// Path of the folder inside the bundle, e.g. `project`.
    pub path: String,
    /// Pages in the folder and everything below it.
    pub pages: usize,
}

/// What one folder holds: its sub-folders, and its own pages.
#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct Listing {
    /// The folder's path inside the bundle; empty for the root.
    pub dir: String,
    pub folders: Vec<FolderEntry>,
    /// The folder's `home.md` first, then the other pages by title.
    pub pages: Vec<PageEntry>,
    /// Journal pages, newest first.
    pub journal: Vec<PageEntry>,
}

/// The listing of one folder (`""` is the root).
pub fn listing(bundle: &Bundle, dir: &str) -> Listing {
    build(bundle, dir, false)
}

/// Every page below a folder, sub-folders included, as one flat listing: `folders` is
/// empty, and each entry's `path` says where the page is.
pub fn recursive_listing(bundle: &Bundle, dir: &str) -> Listing {
    build(bundle, dir, true)
}

fn build(bundle: &Bundle, dir: &str, recursive: bool) -> Listing {
    let dir = dir.trim_matches('/');
    let prefix = if dir.is_empty() {
        String::new()
    } else {
        format!("{dir}/")
    };
    let mut folders: BTreeMap<String, usize> = BTreeMap::new();
    let mut pages = Vec::new();
    let mut journal = Vec::new();
    for page in &bundle.pages {
        let Some(rest) = page.path.strip_prefix(&prefix) else {
            continue;
        };
        if let Some((folder, _)) = rest.split_once('/')
            && !recursive
        {
            *folders.entry(format!("{prefix}{folder}")).or_default() += 1;
            continue;
        }
        let entry = entry_of(page);
        if page.kind() == Some("journal") {
            journal.push(entry);
        } else {
            pages.push(entry);
        }
    }
    // A folder's own pages come before the ones in its sub-folders.
    pages.sort_by_key(|e| {
        let (folder, file) = e.path.rsplit_once('/').unwrap_or(("", &e.path));
        (
            folder.split('/').map(str::to_string).collect::<Vec<_>>(),
            file != "home.md",
            e.title.to_lowercase(),
            e.path.clone(),
        )
    });
    journal.sort_by(|a, b| b.path.cmp(&a.path));
    Listing {
        dir: dir.to_string(),
        folders: folders
            .into_iter()
            .map(|(path, pages)| FolderEntry { path, pages })
            .collect(),
        pages,
        journal,
    }
}

/// The listings of the root and of every folder below it that holds pages.
pub fn listings(bundle: &Bundle) -> Vec<Listing> {
    let mut dirs: BTreeSet<String> = BTreeSet::new();
    dirs.insert(String::new());
    for page in &bundle.pages {
        let mut dir = page.path.as_str();
        while let Some((parent, _)) = dir.rsplit_once('/') {
            dirs.insert(parent.to_string());
            dir = parent;
        }
    }
    dirs.iter().map(|d| listing(bundle, d)).collect()
}

impl Listing {
    /// The listing as an OKF `index.md` (§6). `name` titles the root.
    pub fn to_markdown(&self, name: &str) -> String {
        let prefix = if self.dir.is_empty() {
            String::new()
        } else {
            format!("{}/", self.dir)
        };
        let mut out = String::new();
        if self.dir.is_empty() {
            out.push_str("---\nokf_version: \"0.2\"\n---\n\n");
        }
        out.push_str(MARKER);
        out.push_str("\n\n# ");
        out.push_str(if self.dir.is_empty() { name } else { &self.dir });
        out.push('\n');
        if !self.folders.is_empty() {
            out.push_str("\n## Folders\n\n");
            for folder in &self.folders {
                let label = folder.path.rsplit('/').next().unwrap_or(&folder.path);
                let unit = if folder.pages == 1 { "page" } else { "pages" };
                out.push_str(&format!(
                    "* [{}]({label}/index.md) - {} {unit}\n",
                    link_text(label),
                    folder.pages
                ));
            }
        }
        for (heading, entries) in [("Pages", &self.pages), ("Journal", &self.journal)] {
            if entries.is_empty() {
                continue;
            }
            out.push_str(&format!("\n## {heading}\n\n"));
            for e in entries {
                // Relative to the folder, so a flat listing of sub-folders still links.
                let file = e.path.strip_prefix(&prefix).unwrap_or(&e.path);
                out.push_str(&format!("* [{}]({file})", link_text(&e.title)));
                if let Some(d) = &e.description {
                    out.push_str(&format!(" - {d}"));
                }
                out.push('\n');
            }
        }
        out
    }
}

#[derive(Debug, Default, Serialize, schemars::JsonSchema)]
pub struct WriteReport {
    /// Index files written, as bundle paths.
    pub written: Vec<String>,
    /// Existing `index.md` files left alone because they are not generated.
    pub kept: Vec<String>,
}

/// Write an `index.md` into the root and every folder that holds pages. A file that
/// exists without the generated marker is kept unless `force` is set.
pub fn write_indexes(bundle: &Bundle, force: bool) -> io::Result<WriteReport> {
    let name = bundle
        .root
        .canonicalize()
        .ok()
        .and_then(|p| p.file_name().map(|n| n.to_string_lossy().into_owned()))
        .unwrap_or_else(|| "Notes".into());
    let mut report = WriteReport::default();
    for listing in listings(bundle) {
        let rel = if listing.dir.is_empty() {
            "index.md".to_string()
        } else {
            format!("{}/index.md", listing.dir)
        };
        let path = bundle.root.join(&rel);
        if path.exists() && !force && !is_generated(&path)? {
            report.kept.push(rel);
            continue;
        }
        std::fs::write(&path, listing.to_markdown(&name))?;
        report.written.push(rel);
    }
    Ok(report)
}

fn is_generated(path: &Path) -> io::Result<bool> {
    Ok(std::fs::read_to_string(path)?
        .lines()
        .any(|l| l.trim() == MARKER))
}

fn entry_of(page: &Page) -> PageEntry {
    let file = page.path.rsplit('/').next().unwrap_or(&page.path);
    let title = page
        .get_str("title")
        .map(str::to_string)
        .unwrap_or_else(|| file.trim_end_matches(".md").to_string());
    let description = page
        .get_str("description")
        .map(str::to_string)
        .or_else(|| page.blocks.first().map(|b| b.text.clone()))
        .and_then(|text| shorten(&text));
    PageEntry {
        path: page.path.clone(),
        title,
        description,
        kind: page.kind().map(str::to_string),
    }
}

/// The first line of some text, short enough for one list entry.
fn shorten(text: &str) -> Option<String> {
    let line = text.lines().map(str::trim).find(|l| !l.is_empty())?;
    let mut out: String = line.chars().take(DESCRIPTION_CHARS).collect();
    if out.chars().count() < line.chars().count() {
        out = out.trim_end().to_string() + "…";
    }
    Some(out)
}

/// Link text cannot hold square brackets.
fn link_text(text: &str) -> String {
    text.replace('[', "(").replace(']', ")")
}
